def test_oneline_strips_emoji_tofu():
    # windchime global_name: two emoji became .notdef boxes beside the name
    assert _oneline("windchime \U0001f390\U0001f9ff") == "windchime"
    assert _oneline("魔法少女") == "魔法少女"


def test_parse_progress_thousand_commas():
    """12,688 / 50,000 must not become 688/50 (old regex bug)."""
    ratio, label = _parse_progress("12,688 / 50,000 characters · Tadoku")
    assert ratio is not None
    assert abs(ratio - 12688 / 50000) < 1e-9
    assert "12,688" in label and "50,000" in label
    assert "688 / 50" not in label.replace("12,688 / 50,000", "")
    r2, _ = _parse_progress("6.2 / 10 volumes")
    assert r2 is not None and abs(r2 - 0.62) < 1e-9
    r3, _ = _parse_progress("32.1k / 30k characters")
    assert r3 is not None and abs(r3 - 32100 / 30000) < 1e-9

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "data" / "card_previews"


def test_print_every_card_format():
    """Render every card kind to data/card_previews/ and print paths."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    cards = asyncio.run(render_all_demo_cards())
    extra = ("userinfo", "leaderboard")
    kinds_expected = [k for k in KIND_STYLE if k not in extra] + list(extra)
    assert [k for k, _ in cards] == kinds_expected
    assert set(DEMO_CHALLENGE_SAMPLES) == set(kinds_expected) - set(extra)

    written: list[Path] = []
    for kind, png in cards:
        assert png[:8] == b"\x89PNG\r\n\x1a\n", kind
        path = OUT_DIR / f"card_{kind}.png"
        path.write_bytes(png)
        written.append(path)
        print(f"CARD {kind:12} → {path} ({len(png)} bytes)")

    index = OUT_DIR / "README.txt"
    index.write_text(
        "ChallengeTracker card previews\n"
        "Generated by tests.test_challenge_card.test_print_every_card_format\n\n"
        + "\n".join(p.name for p in written)
        + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(written)} cards under {OUT_DIR}")
    assert len(written) == 10


def test_multi_works_grows_card_height():
    """Card height scales with works count (dynamic per entry)."""
    from PIL import Image
    import io

    def _h(n: int) -> int:
        focus = "\n".join(f"Work title number {i}" for i in range(n))
        png = asyncio.run(
            render_challenge_card(
                kind="complete",
                display_name="Monty",
                challenge_title="Manga Mini-Marathon",
                tier="easy",
                number=1,
                avatar_bytes=None,
                focus=focus,
                line_primary="Cleared",
                line_secondary="Tadoku",
                footer="ChallengeTracker",
            )
        )
        return Image.open(io.BytesIO(png)).size[1]

    h1, h4, h6 = _h(1), _h(4), _h(6)
    assert h4 > h1
    assert h6 > h4
    # roughly linear: each extra entry adds ~20px
    assert (h6 - h4) >= 30
    multi = asyncio.run(
        render_challenge_card(
            kind="complete",
            display_name="Monty",
            challenge_title="Manga Mini-Marathon",
            tier="easy",
            number=1,
            avatar_bytes=None,
            focus="One Piece\nSand Land\nDr. Slump\nDragon Ball",
            line_primary="Cleared",
            line_secondary="Tadoku",
            footer="ChallengeTracker",
        )
    )
    path = OUT_DIR / "card_multi_works.png"
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path.write_bytes(multi)
    print(f"CARD multi_works → {path} (1={h1} 4={h4} 6={h6}px)")


def test_poster_on_card():
    """Synthetic cover art appears on the right without breaking layout."""
    from PIL import Image, ImageDraw
    import io

    img = Image.new("RGB", (200, 300), (40, 80, 160))
    d = ImageDraw.Draw(img)
    d.rectangle((20, 20, 180, 280), outline=(255, 255, 255), width=3)
    d.text((40, 140), "COVER", fill=(255, 255, 255))
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    cover = buf.getvalue()

    png = asyncio.run(
        render_challenge_card(
            kind="complete",
            display_name="Monty",
            challenge_title="VN 30k",
            tier="easy",
            number=4,
            avatar_bytes=None,
            focus="Steins;Gate",
            line_primary="Cleared",
            line_secondary="Tadoku",
            footer="ChallengeTracker",
            poster_bytes=cover,
        )
    )
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
    # Poster widens the card vs no-poster baseline
    bare = asyncio.run(
        render_challenge_card(
            kind="complete",
            display_name="Monty",
            challenge_title="VN 30k",
            tier="easy",
            number=4,
            avatar_bytes=None,
            focus="Steins;Gate",
            line_primary="Cleared",
            line_secondary="Tadoku",
            footer="ChallengeTracker",
            poster_bytes=None,
        )
    )
    from PIL import Image as _Image

    w_poster = _Image.open(__import__("io").BytesIO(png)).size[0]
    w_bare = _Image.open(__import__("io").BytesIO(bare)).size[0]
    assert w_poster > w_bare
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / "card_with_poster.png"
    path.write_bytes(png)
    print(f"CARD with_poster → {path} ({len(png)} bytes)")


