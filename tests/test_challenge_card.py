"""PNG challenge cards — render every format and write previews to disk."""

from __future__ import annotations

import asyncio
from pathlib import Path

from app.challenge_card import (
    DEMO_CHALLENGE_SAMPLES,
    KIND_STYLE,
    render_all_demo_cards,
    render_challenge_card,
    render_leaderboard_card,
)

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "data" / "card_previews"


def test_print_every_card_format():
    """Render every card kind to data/card_previews/ and print paths."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    cards = asyncio.run(render_all_demo_cards())
    kinds_expected = [k for k in KIND_STYLE if k != "leaderboard"] + ["leaderboard"]
    assert [k for k, _ in cards] == kinds_expected
    assert set(DEMO_CHALLENGE_SAMPLES) == set(kinds_expected) - {"leaderboard"}

    written: list[Path] = []
    for kind, png in cards:
        assert png[:8] == b"\x89PNG\r\n\x1a\n", kind
        path = OUT_DIR / f"card_{kind}.png"
        path.write_bytes(png)
        written.append(path)
        print(f"CARD {kind:12} → {path} ({len(png)} bytes)")

    index = OUT_DIR / "README.txt"
    index.write_text(
        "ChallengeTracker card previews\n"
        "Generated by tests.test_challenge_card.test_print_every_card_format\n\n"
        + "\n".join(p.name for p in written)
        + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(written)} cards under {OUT_DIR}")
    assert len(written) == 9


def test_poster_on_card():
    """Synthetic cover art appears on the right without breaking layout."""
    from PIL import Image, ImageDraw
    import io

    img = Image.new("RGB", (200, 300), (40, 80, 160))
    d = ImageDraw.Draw(img)
    d.rectangle((20, 20, 180, 280), outline=(255, 255, 255), width=3)
    d.text((40, 140), "COVER", fill=(255, 255, 255))
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    cover = buf.getvalue()

    png = asyncio.run(
        render_challenge_card(
            kind="complete",
            display_name="Monty",
            challenge_title="VN 30k",
            tier="easy",
            number=4,
            avatar_bytes=None,
            focus="Steins;Gate",
            line_primary="Cleared",
            line_secondary="Tadoku",
            footer="ChallengeTracker",
            poster_bytes=cover,
        )
    )
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
    # Poster widens the card vs no-poster baseline
    bare = asyncio.run(
        render_challenge_card(
            kind="complete",
            display_name="Monty",
            challenge_title="VN 30k",
            tier="easy",
            number=4,
            avatar_bytes=None,
            focus="Steins;Gate",
            line_primary="Cleared",
            line_secondary="Tadoku",
            footer="ChallengeTracker",
            poster_bytes=None,
        )
    )
    from PIL import Image as _Image

    w_poster = _Image.open(__import__("io").BytesIO(png)).size[0]
    w_bare = _Image.open(__import__("io").BytesIO(bare)).size[0]
    assert w_poster > w_bare
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / "card_with_poster.png"
    path.write_bytes(png)
    print(f"CARD with_poster → {path} ({len(png)} bytes)")


